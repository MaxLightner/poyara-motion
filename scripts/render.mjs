import {readFileSync, mkdirSync, existsSync} from 'node:fs';
import {resolve} from 'node:path';
import {spawnSync} from 'node:child_process';
import {postSchema} from '../src/projects/poyara/schema.mjs';
const [input = 'src/projects/poyara/posts/sample.json', format = 'square', output = 'out/poyara-sample.mp4'] = process.argv.slice(2);
if (!['square','portrait'].includes(format)) throw new Error('Format must be square or portrait');
if (!output.endsWith('.mp4')) throw new Error('Output must end in .mp4');
const effectiveInput = input.startsWith('posts/') && !existsSync(input) ? 'src/projects/poyara/'+input : input;
postSchema.parse(JSON.parse(readFileSync(resolve(effectiveInput),'utf8')));
mkdirSync(resolve(output,'..'),{recursive:true});
const cli=resolve('node_modules/@remotion/cli/remotion-cli.js');
if(!existsSync(cli)) throw new Error('Run npm ci first');
const browser=process.env.REMOTION_BROWSER_EXECUTABLE;
const result=spawnSync(process.execPath,[cli,'render','src/index.tsx',format==='square'?'PoyaraSquare':'PoyaraPortrait',resolve(output),`--props=${resolve(effectiveInput)}`,'--codec=h264','--pixel-format=yuv420p','--crf=18','--concurrency=2',...(browser?[`--browser-executable=${browser}`]:[])],{stdio:'inherit'});
process.exit(result.status??1);
